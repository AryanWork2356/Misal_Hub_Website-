/**
 * Builds src/styles/<page>.css from the ORIGINAL static-site stylesheets in /legacy.
 *
 * Why: the static site loads a different set of CSS per page, and those files reuse the
 * same class names and @keyframes names with different meanings. In a Next.js app all CSS
 * can end up on screen at once, so each page's CSS is scoped under its own wrapper class
 * (.pg-home, .pg-menu, ...) and its keyframes are renamed. The rules themselves are not changed,
 * which is what keeps the pages looking identical to the static version.
 *
 * Run:  node scripts/scope-css.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';
import prefixer from 'postcss-prefix-selector';

const root = path.resolve(import.meta.dirname, '..');
const pages = {
  home: ['style.css', 'theme.css', 'premium.css'],
  menu: ['style.css', 'theme.css', 'premium.css', 'order.css'],
  about: ['about.css', 'theme.css', 'premium.css'],
  franchise: ['franchise.css', 'theme.css', 'premium.css'],
};

for (const [page, files] of Object.entries(pages)) {
  const wrap = `.pg-${page}`;
  let css = files.map((f) => fs.readFileSync(path.join(root, 'legacy', f), 'utf8')).join('\n');
  css = css.replace(/@import\s+url\([^)]*\)\s*;?/g, ''); // fonts are linked in layout.tsx

  const ast = postcss.parse(css);

  // 1) rename keyframes so pages cannot collide
  const kf = new Map();
  ast.walkAtRules(/keyframes$/i, (r) => { kf.set(r.params, `${page}-${r.params}`); r.params = `${page}-${r.params}`; });
  ast.walkDecls(/^animation(-name)?$/i, (d) => {
    let v = d.value;
    for (const [from, to] of kf) v = v.replace(new RegExp(`(^|[\\s,])${from}(?=[\\s,;]|$)`, 'g'), `$1${to}`);
    d.value = v;
  });

  // 2) scope every selector under the page wrapper
  const out = await postcss([
    prefixer({
      prefix: wrap,
      transform(prefix, selector, prefixed) {
        const s = selector.trim();
        if (/^html\b/.test(s) || /^\.lenis\b/.test(s)) return s;          // document-level (Lenis)
        if (s.startsWith('::-webkit-scrollbar')) return s;                 // page-level scrollbar
        if (s === ':root') return prefix;                                  // CSS variables live on the wrapper
        if (/^body\b/.test(s)) return s.replace(/^body/, prefix);          // body styles -> wrapper
        return prefixed;
      },
    }),
  ]).process(ast, { from: undefined });

  // 3) the wrapper replaces <body>: overflow-x:hidden would break position:sticky, clip does not
  out.root.walkRules((r) => {
    if (r.selector === wrap) r.walkDecls('overflow-x', (d) => { if (d.value === 'hidden') d.value = 'clip'; });
  });

  const header = `/* GENERATED by scripts/scope-css.mjs from legacy/{${files.join(',')}} — do not edit by hand */\n`;
  fs.writeFileSync(path.join(root, 'src/styles', `${page}.css`), header + out.root.toString());
  console.log(page.padEnd(10), files.join(' + '), '->', `${wrap}`, `(${kf.size} keyframes renamed)`);
}
